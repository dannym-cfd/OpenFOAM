def junction_box(stl):
    # Where the wing root passes through the fuselage skin: its vertices near
    # r = SKIN_R, padded 10 mm along the chord, a band across the skin and
    # wide enough in y to take in the slot.
    d = open(stl, "rb").read()
    n = struct.unpack("<I", d[80:84])[0]
    zs, xs = [], []
    for i in range(n):
        v = struct.unpack_from("<12f", d, 84 + 50 * i)
        for j in range(3):
            x, z = v[3 + 3 * j], v[5 + 3 * j]
            if SKIN_R - 0.004 < abs(x) < SKIN_R + 0.006:
                xs.append(x)
                zs.append(z)
    sgn = 1.0 if sum(xs) > 0 else -1.0
    x0, x1 = sorted((sgn * 0.040, sgn * 0.065))
    return (x0, -0.020, min(zs) - 0.010), (x1, 0.020, max(zs) + 0.010)

def snappy_dict(case):
    s = os.path.join(case, "system")
    tri = os.path.join(case, "constant", "triSurface")
    boxes = {"junctionLeft": junction_box(os.path.join(tri, "leftwing.stl")),
             "junctionRight": junction_box(os.path.join(tri, "rightwing.stl"))}
    geom = "".join("    %s.stl\n    {\n        type triSurfaceMesh;\n        name %s;\n    }\n" % (w, w) for w in WALLS)
    geom += "".join("    %-13s { type searchableBox; min %s; max %s; }\n" % (b, vec(lo), vec(hi))
                    for b, (lo, hi) in boxes.items())
    sfe = "".join("%s.stl\n{\n    extractionMethod    extractFromSurface;\n    extractFromSurfaceCoeffs { includedAngle 150; }\n    subsetFeatures { nonManifoldEdges yes; openEdges yes; }\n    writeObj            no;\n}\n\n" % w for w in WALLS)
    sfe += ("wingJunction\n{\n    extractionMethod    none;\n    surfaces            (%s);\n"
            "    intersectionMethod  self;\n    writeObj            no;\n}\n"
            % " ".join(w + ".stl" for w in JUNCTION_SURFACES))
    write(os.path.join(s, "surfaceFeatureExtractDict"), header("dictionary", "surfaceFeatureExtractDict", "system") + sfe)
    feats = "".join('        { file "%s.eMesh"; level %d; }\n' % (w, LEVELS[w][2]) for w in WALLS)
