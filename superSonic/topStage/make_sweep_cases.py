#!/usr/bin/env python3
"""Build the topstage wing-sweep case matrix (one case per sweep angle, same
freestream) for openfoam-ui. Run inside WSL:
    python3 make_sweep_cases.py <geomRoot> <templateRoot> <outRoot> [--mesh-dicts] [--only=86 ...]
--mesh-dicts rewrites only the snappyHexMesh and surfaceFeatureExtract dicts of
cases that already exist; --only=<sweep> limits either mode to those angles.
"""
import math, os, shutil, struct, sys

GEOM, TEMPLATE, OUT = sys.argv[1:4]
SWEEPS = [86, 60, 40, 20, 0]
MACH = 0.70

# --- Freestream: sea-level ISA, 0 deg AoA (same for every sweep angle) ------
ALT = 0.0              # m
AOA = 0.0              # deg, nose up; freestream in the y-z plane
T0, P0, L, G, R, GAM = 288.15, 101325.0, 0.0065, 9.80665, 287.05, 1.4
T = T0 - L * ALT
p = P0 * (T / T0) ** (G / (R * L))
rho = p / (R * T)
a = math.sqrt(GAM * R * T)
Umag = MACH * a
mu = 1.458e-6 * T ** 1.5 / (T + 110.4)
nu = mu / rho
k = 1.5 * (0.001 * Umag) ** 2      # 0.1 % turbulence intensity
omega = k / nu                     # nut/nu = 1 (quiet free flight)
s, c = math.sin(math.radians(AOA)), math.cos(math.radians(AOA))
U = (0.0, Umag * s, -Umag * c)     # body nose points +z, +y is up
liftDir = (0.0, c, s)
dragDir = (0.0, s, -c)

# --- Reference values (identical for every sweep so Cl/Cd compare) ----------
BODY_R = 0.049
AREF = math.pi * BODY_R ** 2       # body frontal area
LREF = 0.966                       # body length, nose tip z=0 to z=-0.966
CG_Z = -0.519155                   # cg_z_m at the Mach 0.7 row, measured from the nose

WALLS = ["nose", "fuselagewing", "fuselagepiece", "finhousing", "bodyFins", "leftwing", "rightwing"]
# surface: (min level, max level, feature level)
LEVELS = {
    "nose": (8, 8, 8),
    "fuselagewing": (8, 8, 8),
    "fuselagepiece": (8, 8, 8),
    "finhousing": (8, 8, 8),
    "bodyFins": (7, 8, 8),
    "leftwing": (8, 9, 9),
    "rightwing": (8, 9, 9),
}
JUNCTION_LEVEL = 9     # box around each wing root where it passes through the skin
# Inside the junction boxes, refine any gap between surfaces until it is at
# least 4 cells across, from level 8 up to level 10 (0.24 mm).
JUNCTION_GAP = (4, 8, 10)
# The wing/skin intersection is a feature of neither STL on its own, so
# surfaceFeatureExtract intersects these surfaces to give snapping that edge.
JUNCTION_SURFACES = ["fuselagewing", "leftwing", "rightwing"]
JUNCTION_FEATURE_LEVEL = 9
SKIN_R = 0.049

def vec(v):
    return "(%s)" % " ".join("%.6g" % x for x in v)

def header(cls, obj, loc=None):
    l = '    location    "%s";\n' % loc if loc else ""
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "  topstage wing sweep, Mach %.2f - generated by make_sweep_cases.py\n"
            "\\*---------------------------------------------------------------------------*/\n"
            "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
            "    class       %s;\n%s    object      %s;\n}\n"
            "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n"
            % (MACH, cls, l, obj))

def write(path, text, exe=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)
    if exe:
        os.chmod(path, 0o755)

def stl_xcentre(path):
    d = open(path, "rb").read()
    n = struct.unpack("<I", d[80:84])[0]
    sx = 0.0
    for i in range(n):
        v = struct.unpack_from("<12f", d, 84 + 50 * i)
        sx += v[3] + v[6] + v[9]
    return sx / (3 * n)

# --------------------------------------------------------------------------- #
def freestream_include():
    return (header("dictionary", "freestreamConditions", "0.orig/include") +
            "// ISA %.0f m, Mach %.2f, AoA %.1f deg (identical for every sweep angle)\n"
            "// a = %.2f m/s, rho = %.5f kg/m^3, mu = %.4e Pa s, Re(L=%.3f m) = %.3e\n\n"
            "Uinf            %s;\n"
            "pInf            %.1f;\n"
            "TInf            %.3f;\n"
            "kInf            %.5g;\n"
            "omegaInf        %.5g;\n"
            % (ALT, MACH, AOA, a, rho, mu, LREF, rho * Umag * LREF / mu,
               vec(U), p, T, k, omega))

def field(cls, obj, dims, internal, farfield, wall):
    walls = "".join("    %s\n    {\n%s    }\n" % (w, wall) for w in WALLS)
    return (header(cls, obj) +
            '#include "include/freestreamConditions"\n\n'
            "dimensions      %s;\n\ninternalField   %s;\n\nboundaryField\n{\n"
            "    farfield\n    {\n%s    }\n%s}\n" % (dims, internal, farfield, walls))

def zero_orig(case):
    o = os.path.join(case, "0.orig")
    write(os.path.join(o, "include", "freestreamConditions"), freestream_include())
    write(os.path.join(o, "U"), field("volVectorField", "U", "[0 1 -1 0 0 0 0]", "uniform $Uinf",
        "        type            freestreamVelocity;\n        freestreamValue uniform $Uinf;\n        value           uniform $Uinf;\n",
        "        type            noSlip;\n"))
    write(os.path.join(o, "p"), field("volScalarField", "p", "[1 -1 -2 0 0 0 0]", "uniform $pInf",
        "        type            freestreamPressure;\n        freestreamValue uniform $pInf;\n        value           uniform $pInf;\n",
        "        type            zeroGradient;\n"))
    write(os.path.join(o, "T"), field("volScalarField", "T", "[0 0 0 1 0 0 0]", "uniform $TInf",
        "        type            inletOutlet;\n        inletValue      uniform $TInf;\n        value           uniform $TInf;\n",
        "        type            zeroGradient;\n"))
    write(os.path.join(o, "k"), field("volScalarField", "k", "[0 2 -2 0 0 0 0]", "uniform $kInf",
        "        type            inletOutlet;\n        inletValue      uniform $kInf;\n        value           uniform $kInf;\n",
        "        type            kqRWallFunction;\n        value           uniform $kInf;\n"))
    write(os.path.join(o, "omega"), field("volScalarField", "omega", "[0 0 -1 0 0 0 0]", "uniform $omegaInf",
        "        type            inletOutlet;\n        inletValue      uniform $omegaInf;\n        value           uniform $omegaInf;\n",
        "        type            omegaWallFunction;\n        value           uniform $omegaInf;\n"))
    write(os.path.join(o, "nut"), field("volScalarField", "nut", "[0 2 -1 0 0 0 0]", "uniform 0",
        "        type            calculated;\n        value           uniform 0;\n",
        "        type            nutUSpaldingWallFunction;\n        value           uniform 0;\n"))
    write(os.path.join(o, "alphat"), field("volScalarField", "alphat", "[1 -1 -1 0 0 0 0]", "uniform 0",
        "        type            calculated;\n        value           uniform 0;\n",
        "        type            compressible::alphatWallFunction;\n        Prt             0.85;\n        value           uniform 0;\n"))

