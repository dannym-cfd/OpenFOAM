def geometry(case, sweep):
    tri = os.path.join(case, "constant", "triSurface")
    os.makedirs(tri, exist_ok=True)
    src = os.path.join(GEOM, "topstage%d" % sweep)
    # Left/right by physical side: flight +z, up +y -> the vehicle's left is +x.
    wings = [os.path.join(src, f) for f in ("leftwing.stl", "rightwing.stl")]
    xs = [stl_xcentre(w) for w in wings]
    left, right = (wings[0], wings[1]) if xs[0] > xs[1] else (wings[1], wings[0])
    shutil.copyfile(left, os.path.join(tri, "leftwing.stl"))
    shutil.copyfile(right, os.path.join(tri, "rightwing.stl"))
    for w in WALLS:
        if w in ("leftwing", "rightwing"):
            continue
        shutil.copyfile(os.path.join(src, w + ".stl"), os.path.join(tri, w + ".stl"))
    for w in WALLS:
        clear_stl_regions(os.path.join(tri, w + ".stl"))
    return "swapped" if left == wings[1] else "as-is"

def clear_stl_regions(path):
    # Binary STL: OpenFOAM reads each triangle's 2-byte attribute as a region
    # id, so a non-zero one splits the part into <name>_patchN patches.
    d = bytearray(open(path, "rb").read())
    n = struct.unpack("<I", d[80:84])[0]
    for i in range(n):
        o = 84 + 50 * i + 48
        d[o] = d[o + 1] = 0
    open(path, "wb").write(d)

def scripts(case):
    for f in ("Allmesh", "Allclean"):
        shutil.copyfile(os.path.join(TEMPLATE, f), os.path.join(case, f))
        os.chmod(os.path.join(case, f), 0o755)

# --------------------------------------------------------------------------- #
print("Freestream: T=%.3f K p=%.1f Pa rho=%.5f a=%.3f U=%.3f m/s Re=%.3e k=%.4g omega=%.4g"
      % (T, p, rho, a, Umag, rho * Umag * LREF / mu, k, omega))
MESH_DICTS_ONLY = "--mesh-dicts" in sys.argv[4:]
ONLY = [int(a.split("=")[1]) for a in sys.argv[4:] if a.startswith("--only=")]
for sw in SWEEPS:
    if ONLY and sw not in ONLY:
        continue
    case = os.path.join(OUT, "topstage%02d_M%.2f" % (sw, MACH))
    if MESH_DICTS_ONLY:
        if os.path.exists(case):
            snappy_dict(case)
            print("rewrote %s/system/{snappyHexMeshDict,surfaceFeatureExtractDict}" % case)
        continue
    if os.path.exists(case):
        print("skip (exists):", case)
        continue
    zero_orig(case)
    constant(case)
    w = geometry(case, sw)
    system(case, sw)
    scripts(case)
    print("wrote %s  (wings %s)" % (case, w))
